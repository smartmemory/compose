function setupProofProject(tmpDir) {
  const composeDir = join(tmpDir, '.compose');
  mkdirSync(join(composeDir, 'data'), { recursive: true });
  writeFileSync(
    join(composeDir, 'compose.json'),
    JSON.stringify({ version: '1.0', capabilities: { stratum: true } })
  );

  const featureDir = join(tmpDir, 'docs', 'features', 'PROOF-1');
  mkdirSync(featureDir, { recursive: true });
  writeFileSync(join(featureDir, 'design.md'), '# Proof Run\nValidating compose build pipeline.');

  const pipeDir = join(tmpDir, 'pipelines');
  mkdirSync(pipeDir, { recursive: true });
  const realSpec = join(ROOT, '..', 'pipelines', 'build.stratum.yaml');
  // C5 (ruling): proof-run exercises the production build.stratum.yaml UNMODIFIED.
  // Ship's unevaluable `judged` ensure was removed at the source (it failed closed
  // from the judge's {result, input} even on evidenced results — it would have
  // killed real TS-default builds at ship); ship remains gated by ship_gate.
  const fixtureSpec = readFileSync(realSpec, 'utf8');
  writeFileSync(join(pipeDir, 'build.stratum.yaml'), fixtureSpec);

  mkdirSync(join(tmpDir, 'src'), { recursive: true });
  writeFileSync(join(tmpDir, 'src', 'util.js'), 'export const util = true;\n');
  execFileSync('git', ['init', '-q'], { cwd: tmpDir });
  execFileSync('git', ['config', 'user.email', 'proof@example.com'], { cwd: tmpDir });
  execFileSync('git', ['config', 'user.name', 'Proof Test'], { cwd: tmpDir });
  execFileSync('git', ['add', '.'], { cwd: tmpDir });
  execFileSync('git', ['commit', '-qm', 'fixture'], { cwd: tmpDir });

  return { composeDir, featureDir, pipeDir };
}

