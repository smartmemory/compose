/**
 * Creates a connector factory that returns canned results per step.
 * Tracks which steps were dispatched and with which agent type.
 * Creates artifact files that stratum's file_exists ensures check for.
 *
 * @param {Array}  dispatches  - Collects { stepId, agentType, promptSnippet }
 * @param {string} featureDir  - Path to the feature folder for artifact creation
 * @param {object} [overrides] - Per-step result overrides: { stepId: result }
 */
function mockConnectorFactory(dispatches, featureDir, overrides = {}) {
  // Map step IDs to the artifact files their ensure conditions expect.
  // The result.artifact field must match for file_exists(result.artifact) to pass.
  const artifactMap = {
    explore_design: 'design.md',
    blueprint: 'blueprint.md',
    plan: 'plan.md',
  };

  return function factory(agentType, connectorOpts) {
    return {
      async *run(prompt, _runOpts) {
        // Extract step_id from the prompt (format: step "step_id")
        const stepMatch = prompt.match(/step "([^"]+)"/);
        const stepId = stepMatch?.[1] ?? 'unknown';
        const bareStepId = stepId.split('/').at(-1);

        dispatches.push({ stepId, bareStepId, agentType, promptSnippet: prompt.slice(0, 120) });

        // Create artifact file if this step produces one
        const artifactFile = artifactMap[bareStepId];
        if (artifactFile) {
          mkdirSync(featureDir, { recursive: true });
          writeFileSync(
            join(featureDir, artifactFile),
            `# ${bareStepId}\nGenerated by mock connector.`
          );
        }

        // Consumer worktree dispatches must leave a real retained diff.
        if (stepId.startsWith('execute/')) {
          const worktree = connectorOpts?.cwd;
          mkdirSync(join(worktree, 'src'), { recursive: true });
          writeFileSync(join(worktree, 'src', 'main.js'), 'export const proof = true;\n');
        }

        // Check for per-step overrides
        const overrideValue = overrides[stepId] ?? overrides[bareStepId];
        if (overrideValue) {
          const override = typeof overrideValue === 'function'
            ? overrideValue(dispatches)
            : overrideValue;
          yield { type: 'assistant', content: JSON.stringify(override) };
          yield { type: 'system', subtype: 'complete', agent: 'mock' };
          return;
        }

        // Default contract-matching result
        const result = getStepResult(stepId, featureDir);
        yield { type: 'assistant', content: JSON.stringify(result) };
        yield { type: 'system', subtype: 'complete', agent: 'mock' };
      },
      interrupt() {},
      get isRunning() { return false; },
    };
  };
}

function getStepResult(stepId, featureDir) {
  const bareStepId = stepId.split('/').at(-1);
  const artifactMap = {
    explore_design: 'design.md',
    blueprint: 'blueprint.md',
    plan: 'plan.md',
  };
  const artifactFile = artifactMap[bareStepId];
  // For PhaseResult steps: artifact must be relative path that file_exists can verify
  const artifactPath = artifactFile
    ? `docs/features/${featureDir.split('/').pop()}/${artifactFile}`
    : `${stepId}.md`;

  const phaseResult = {
    phase: bareStepId,
    artifact: artifactPath,
    outcome: 'complete',
    summary: `${bareStepId} completed`,
  };
  const reviewResult = {
    clean: true, summary: 'No issues found', findings: [], meta: {},
    lenses_run: [], auto_fixes: [], asks: [],
  };
  const testResult = { passing: true, summary: 'All tests pass', failures: [] };
  const taskGraph = {
    tasks: [
      {
        id: 'task-1',
        description: 'Implement the main feature logic',
        files_owned: ['src/main.js'],
        files_read: ['src/util.js'],
        depends_on: [],
      },
    ],
  };

  // Triage result for parallel_review sub-flow
  const triageResult = {
    tasks: [
      { id: 'diff-quality', lens_name: 'diff-quality', lens_focus: 'diff quality', confidence_gate: 0.7, exclusions: '' },
      { id: 'contract-compliance', lens_name: 'contract-compliance', lens_focus: 'contract', confidence_gate: 0.7, exclusions: '' },
    ],
  };
  // Lens finding result (clean)
  const lensResult = { ...reviewResult, summary: 'Lens clean' };
  // Merged review result
  const mergedReviewResult = { clean: true, summary: 'No issues found', findings: [], must_fix_count: 0 };

  if (stepId.startsWith('execute/')) {
    return { outcome: 'complete', summary: 'Task implemented', files_changed: ['src/main.js'] };
  }
  if (stepId.startsWith('review_lenses/')) return lensResult;

  switch (bareStepId) {
    case 'decompose': return taskGraph;
    case 'review': return reviewResult;
    case 'triage':
    case 'review_triage': return triageResult;
    case 'review_lenses': return lensResult;
    case 'diff-quality': return lensResult;
    case 'contract-compliance': return lensResult;
    case 'debug-discipline': return lensResult;
    case 'security': return lensResult;
    case 'framework': return lensResult;
    case 'merge':
    case 'merge_review':
    case 'review_merge': return { ...reviewResult, ...mergedReviewResult };
    case 'review_check': return reviewResult;
    case 'run_tests': return testResult;
    case 'coverage_check': return testResult;
    case 'ship': return {
      ...phaseResult,
      plan_items: [{ text: 'test item', file: 'src/main.js', critical: false }],
      files_changed: ['src/main.js'],
    };
    default: return phaseResult;
  }
}

// ---------------------------------------------------------------------------
// Gate auto-approve helper
// ---------------------------------------------------------------------------

function createAutoApproveGateOpts() {
  const output = new PassThrough();
  output.on('data', () => {}); // drain

  return {
    get input() {
      const input = new PassThrough();
      setImmediate(() => {
        input.write('a\n');
        setImmediate(() => { input.write('LGTM\n'); });
      });
      return input;
    },
    output,
  };
}

