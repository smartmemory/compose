#!/usr/bin/env node
/**
 * gen-stub.js — renders the project ontology pack into the type stub each forge app's `ontology/` seam commits
 * (FORGE-ONTOLOGY-READY-1). Deterministic: the same pack bytes give the same file, and every seam's test re-renders
 * and diffs, so a pack change shows up as a red test instead of a silent drift.
 *
 * A STUB until ONTO-PROJECT-PACK-1 phase B: core will emit `.d.ts` and JSON Schemas under the pack's `generated/`
 * dir; until then the JSON Schemas here are derived from each type's `properties_schema` (core field spec,
 * `smartmemory/record_schema.py:8-12`) the same way core's `validate_item_fields` reads it: required =
 * `required_properties`, extra fields allowed.
 *
 *   node lib/ontology/gen-stub.js --format js|ts|dts --out <file>
 */
import { writeFileSync } from 'node:fs';
import { relative } from 'node:path';
import { findSmartMemoryRoot, resolveOntologyPack } from './resolve-pack.js';

const TS_OF = { string: 'string', datetime: 'string', integer: 'number', number: 'number', boolean: 'boolean', object: 'Record<string, unknown>' };
const SCHEMA_OF = {
  string: { type: 'string' }, datetime: { type: 'string', format: 'date-time' }, integer: { type: 'integer' },
  number: { type: 'number' }, boolean: { type: 'boolean' }, object: { type: 'object' },
};

const tsType = (spec) => (spec.type === 'list' ? `${TS_OF[spec.of] ?? 'unknown'}[]` : TS_OF[spec.type] ?? 'unknown');
const fieldSchema = (spec) => (spec.type === 'list' ? { type: 'array', items: SCHEMA_OF[spec.of] ?? {} } : SCHEMA_OF[spec.type] ?? {});

/** One JSON Schema per pack type, keyed by type name. */
export function jsonSchemas(pack) {
  const out = {};
  for (const t of pack.types) {
    const props = {};
    for (const [name, spec] of Object.entries(t.properties_schema ?? {})) props[name] = fieldSchema(spec);
    out[t.name] = { $id: `${pack.pack_id}/${pack.pack_version}/${t.name}`, title: t.name, type: 'object', properties: props, required: [...(t.required_properties ?? [])], additionalProperties: true };
  }
  return out;
}

const fields = (t) => Object.entries(t.properties_schema ?? {}).map(([name, spec]) => ({ name, spec, required: (t.required_properties ?? []).includes(name) }));

/**
 * @param {object} pack parsed pack JSON
 * @param {{sha256: string, sourceLabel: string, format: 'js'|'ts'|'dts'}} opts
 */
export function render(pack, { sha256, sourceLabel, format }) {
  const types = pack.types.map((t) => t.name);
  const relations = pack.relations.map((r) => r.name);
  const asConst = format === 'ts' ? ' as const' : '';
  const L = [
    `// GENERATED by forge/compose lib/ontology/gen-stub.js from ${sourceLabel} (sha256 ${sha256}). Do not edit.`,
    `// Regenerate: node <forge>/compose/lib/ontology/gen-stub.js --format ${format} --out <this file>`,
    '// STUB: rendered from the pack JSON until ONTO-PROJECT-PACK-1 phase B ships generated .d.ts and JSON Schemas.',
    '',
  ];
  if (format === 'dts') {
    L.push(`export declare const PACK_ID: ${JSON.stringify(pack.pack_id)};`, `export declare const PACK_VERSION: ${JSON.stringify(pack.pack_version)};`,
      'export declare const PACK_SHA256: string;',
      `export declare const TYPE_NAMES: readonly [${types.map((n) => JSON.stringify(n)).join(', ')}];`,
      `export declare const RELATION_NAMES: readonly [${relations.map((n) => JSON.stringify(n)).join(', ')}];`,
      'export type PackTypeName = (typeof TYPE_NAMES)[number];',
      'export type PackRelationName = (typeof RELATION_NAMES)[number];',
      'export declare const JSON_SCHEMAS: Record<PackTypeName, { $id: string; title: string; type: "object"; properties: Record<string, object>; required: string[]; additionalProperties: true }>;', '');
  } else {
    L.push(`export const PACK_ID = ${JSON.stringify(pack.pack_id)}${asConst};`, `export const PACK_VERSION = ${JSON.stringify(pack.pack_version)}${asConst};`,
      `export const PACK_SHA256 = ${JSON.stringify(sha256)};`,
      `export const TYPE_NAMES = ${JSON.stringify(types)}${asConst};`,
      `export const RELATION_NAMES = ${JSON.stringify(relations)}${asConst};`);
    if (format === 'ts') L.push('export type PackTypeName = (typeof TYPE_NAMES)[number];', 'export type PackRelationName = (typeof RELATION_NAMES)[number];');
    L.push(`export const JSON_SCHEMAS = ${JSON.stringify(jsonSchemas(pack), null, 2)}${asConst};`, '');
  }
  for (const t of pack.types) {
    const doc = `${t.definition} Id: <project>:${t.name}:<key>, key = ${t._key ?? 'see the pack'}`.replace(/\*\//g, '*\\/');
    if (format === 'js') {
      L.push('/**', ` * ${doc}`, ` * @typedef {object} ${t.name}`);
      for (const f of fields(t)) L.push(` * @property {${tsType(f.spec)}} ${f.required ? f.name : `[${f.name}]`}`);
      L.push(' */', '');
    } else {
      L.push(`/** ${doc} */`, `export interface ${t.name} {`);
      for (const f of fields(t)) L.push(`  ${f.name}${f.required ? '' : '?'}: ${tsType(f.spec)};`);
      L.push('}', '');
    }
  }
  if (format === 'js') L.push('export {};', '');
  return L.join('\n');
}

/** `SmartMemory/<path>` for a file inside the SmartMemory checkout, else the absolute path. */
export function sourceLabel(packFile) {
  const sm = findSmartMemoryRoot();
  const rel = sm ? relative(sm, packFile) : null;
  return rel && !rel.startsWith('..') ? `SmartMemory/${rel}` : packFile;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
  const format = arg('--format');
  const out = arg('--out');
  if (!['js', 'ts', 'dts'].includes(format) || !out) { console.error('usage: gen-stub.js --format js|ts|dts --out <file>'); process.exit(2); }
  const found = resolveOntologyPack();
  if (!found) process.exit(1);
  writeFileSync(out, render(found.pack, { sha256: found.sha256, sourceLabel: sourceLabel(found.packFile), format }));
  console.log(`wrote ${out} from ${found.source} ${found.packFile}`);
}
